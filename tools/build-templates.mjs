// Re-run after replacing a PDF in templates/: node tools/build-templates.mjs
import fs from "node:fs";
const b64 = (f) => fs.readFileSync(new URL(`../templates/${f}`, import.meta.url)).toString("base64");
fs.writeFileSync(new URL("../lib/templates.mjs", import.meta.url),
  `// Generated by tools/build-templates.mjs from templates/*.pdf (bundled so Netlify functions don't need disk reads)\n` +
  `export const AGREEMENT_PDF = Buffer.from("${b64("Agreement_Nov2026.pdf")}", "base64");\n` +
  `export const ORDER_PDF = Buffer.from("${b64("Order_Sheet_IS350.pdf")}", "base64");\n`);
console.log("lib/templates.mjs written");
